#include <iostream>
#include <iomanip>
#include <cmath>
#include <windows.h>

using namespace std;

// Просте нарощення
double simpleAccumulation(double P, double i, double n)
{
    return P * (1 + n * i);
}

// Математичне дисконтування
double mathematicalDiscount(double S, double i, double n)
{
    return S / (1 + n * i);
}

// Банківський облік
double bankDiscount(double S, double d, double n)
{
    return S * (1 - n * d);
}

int main()
{
    // Підтримка кирилиці у Windows
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    double P, S;
    double i, d;
    double n;

    cout << "====================================================\n";
    cout << "       ФІНАНСОВИЙ АНАЛІЗ ПРОСТИХ ВІДСОТКІВ\n";
    cout << "====================================================\n\n";

    cout << "Введіть початкову суму P (грн): ";
    cin >> P;

    cout << "Введіть майбутню суму S (грн): ";
    cin >> S;

    cout << "Введіть термін угоди n (років): ";
    cin >> n;

    cout << "Введіть просту відсоткову ставку i (%): ";
    cin >> i;

    cout << "Введіть банківську облікову ставку d (%): ";
    cin >> d;

    // Переводимо відсотки у десятковий вигляд
    i = i / 100;
    d = d / 100;

    cout << fixed << setprecision(2);

    // ==================================================
    // 1. ПОРІВНЯННЯ МАТЕМАТИЧНОГО І БАНКІВСЬКОГО
    //    ДИСКОНТУВАННЯ
    // ==================================================

    cout << "\n====================================================\n";
    cout << "1. ПОРІВНЯННЯ ДИСКОНТУВАННЯ\n";
    cout << "====================================================\n";

    // Математичне дисконтування
    double P_math = mathematicalDiscount(S, i, n);
    double D_math = S - P_math;

    // Банківський облік
    double P_bank = bankDiscount(S, d, n);
    double D_bank = S - P_bank;

    // Дисконтні множники
    double v_math = 1 / (1 + n * i);
    double v_bank = 1 - n * d;

    cout << "\nМАТЕМАТИЧНЕ ДИСКОНТУВАННЯ\n";
    cout << "  Теперішня сума P        = " << P_math << " грн\n";
    cout << "  Дисконт D               = " << D_math << " грн\n";
    cout << "  Дисконтний множник      = " << v_math << "\n";

    cout << "\nБАНКІВСЬКИЙ ОБЛІК\n";
    cout << "  Теперішня сума P        = " << P_bank << " грн\n";
    cout << "  Дисконт D               = " << D_bank << " грн\n";
    cout << "  Дисконтний множник      = " << v_bank << "\n";

    cout << "\n----------------------------------------------------\n";
    cout << "РІЗНИЦЯ МІЖ МЕТОДАМИ\n";
    cout << "----------------------------------------------------\n";

    cout << "Різниця теперішніх сум = "
        << fabs(P_math - P_bank) << " грн\n";

    cout << "Різниця дисконтів      = "
        << fabs(D_math - D_bank) << " грн\n";

    // ==================================================
    // 2. НАРОЩЕННЯ І МАТЕМАТИЧНЕ ДИСКОНТУВАННЯ
    // ==================================================

    cout << "\n====================================================\n";
    cout << "2. НАРОЩЕННЯ І ДИСКОНТУВАННЯ\n";
    cout << "   ЗА ПРОСТОЮ ВІДСОТКОВОЮ СТАВКОЮ\n";
    cout << "====================================================\n";

    double S_accumulated = simpleAccumulation(P, i, n);

    // Сума відсотків
    double I = S_accumulated - P;

    // Множник нарощення
    double accumulationFactor = 1 + n * i;

    cout << "\nВихідні дані:\n";
    cout << "  Початкова сума P        = " << P << " грн\n";
    cout << "  Ставка i                = " << i * 100 << " %\n";
    cout << "  Термін n                = " << n << " років\n";

    cout << "\nНАРОЩЕННЯ:\n";
    cout << "  Нарощена сума S         = "
        << S_accumulated << " грн\n";

    cout << "  Відсотки I              = "
        << I << " грн\n";

    cout << "  Множник нарощення       = "
        << accumulationFactor << "\n";

    // Дисконтування отриманої нарощеної суми
    double P_returned =
        mathematicalDiscount(S_accumulated, i, n);

    double D_returned =
        S_accumulated - P_returned;

    cout << "\nМАТЕМАТИЧНЕ ДИСКОНТУВАННЯ:\n";
    cout << "  Майбутня сума S         = "
        << S_accumulated << " грн\n";

    cout << "  Теперішня сума P        = "
        << P_returned << " грн\n";

    cout << "  Дисконт D               = "
        << D_returned << " грн\n";

    cout << "  Дисконтний множник      = "
        << 1 / accumulationFactor << "\n";

    // ==================================================
    // 3. ПЕРЕВІРКА РЕЗУЛЬТАТУ
    // ==================================================

    cout << "\n====================================================\n";
    cout << "3. ПЕРЕВІРКА\n";
    cout << "====================================================\n";

    cout << "Початкова сума P          = "
        << P << " грн\n";

    cout << "Повернена сума P          = "
        << P_returned << " грн\n";

    cout << "Різниця                   = "
        << fabs(P - P_returned) << " грн\n";

    // ==================================================
    // 4. КЛЮЧОВІ ФІНАНСОВІ КОЕФІЦІЄНТИ
    // ==================================================

    cout << "\n====================================================\n";
    cout << "4. КЛЮЧОВІ ФІНАНСОВІ КОЕФІЦІЄНТИ\n";
    cout << "====================================================\n";

    cout << "\nМножник нарощення простих відсотків:\n";
    cout << "  1 + n*i = "
        << accumulationFactor << "\n";

    cout << "\nМатематичний дисконтний множник:\n";
    cout << "  1 / (1 + n*i) = "
        << v_math << "\n";

    cout << "\nБанківський дисконтний множник:\n";
    cout << "  1 - n*d = "
        << v_bank << "\n";

    // ==================================================
    // 5. ПЕРЕВІРКА БАНКІВСЬКОГО ДИСКОНТУ
    // ==================================================

    cout << "\n====================================================\n";
    cout << "5. ПЕРЕВІРКА БАНКІВСЬКОГО МЕТОДУ\n";
    cout << "====================================================\n";

    if (1 - n * d > 0)
    {
        cout << "Умова 1 - n*d > 0 виконується.\n";
        cout << "Банківське дисконтування можна застосовувати.\n";
    }
    else
    {
        cout << "УВАГА!\n";
        cout << "Умова 1 - n*d > 0 не виконується.\n";
        cout << "Параметри потребують перевірки.\n";
    }

    cout << "\n====================================================\n";
    cout << "                    КІНЕЦЬ\n";
    cout << "====================================================\n";

    return 0;
}
